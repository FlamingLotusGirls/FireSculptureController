"""Structural interfaces checked by mypy; implementations need not inherit from these."""
from collections.abc import Callable, Iterator
from typing import Any, Protocol

from .Types import (
	AdaptorConfig, AdaptorUpdate, AddressKey, HardwareAddress, LogicalAddress,
	OutputCommands, OutputValue, StateData,
)


class Adaptor(Protocol):
	configData: AdaptorConfig

	def connect(self) -> bool: ...
	def transmitData(self, data: bytes) -> bool: ...
	def updateSerialConnection(self, data: AdaptorUpdate) -> bool: ...
	def stop(self) -> None: ...
	def getCurrentStateData(self) -> StateData: ...


class ProtocolEncoder(Protocol):
	ignoreSafeMode: bool
	translateAddr: Callable[[LogicalAddress], HardwareAddress]

	def formatData(self, addr: HardwareAddress, data: OutputValue) -> bytes: ...
	def formatCommands(self, data: OutputCommands) -> bytes: ...
	def addresses(self) -> Iterator[AddressKey]: ...
	def allOff(self) -> bytes: ...


class InputParameter(Protocol):
	def setValue(self, newValue: Any) -> None: ...
	def getValue(self) -> Any: ...
	def constrain(self, value: Any) -> Any: ...
	def stop(self) -> None: ...
	def getCurrentStateData(self) -> StateData: ...


class Input(Protocol):
	def setInputValue(self, value: Any, settingIndex: int = 0) -> None: ...
	def getValue(self, outputIndex: int = 0) -> Any: ...
	def getId(self) -> int: ...
	def stop(self) -> None: ...
	def getCurrentStateData(self) -> StateData: ...


class InputOwner(Protocol):
	def getId(self) -> str: ...


class Pattern(Protocol):
	def getState(self, row: int, col: int) -> OutputValue: ...
	def setUpdateFunction(self, function: Callable[[], None]) -> None: ...
	def reassignInput(self, *args: Any) -> None: ...
	def getCurrentStateData(self) -> StateData: ...
	def stop(self) -> None: ...


class SculptureModule(Protocol):
	def doCommand(self, command: list[Any]) -> Any: ...
	def getCurrentStateData(self) -> StateData: ...
	def stop(self) -> None: ...
